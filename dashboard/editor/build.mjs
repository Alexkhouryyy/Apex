import {build} from 'esbuild';
import {readFile,writeFile,copyFile,readdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=path.dirname(fileURLToPath(import.meta.url));
const vendor=path.join(root,'../static/vendor');
await build({absWorkingDir:root,entryPoints:['editor.js'],bundle:true,format:'iife',target:'es2022',
  minify:true,legalComments:'linked',outfile:path.join(vendor,'code-editor.js')});
await copyFile(path.join(root,'node_modules/@xterm/xterm/css/xterm.css'),path.join(vendor,'xterm.css'));
const lock=JSON.parse(await readFile(path.join(root,'package-lock.json'),'utf8'));
const notices=['Third-party notices for the bundled Apex Code editor and terminal.\nGenerated by dashboard/editor/build.mjs from package-lock.json.\n'];
for(const [folder,entry] of Object.entries(lock.packages).sort(([a],[b])=>a.localeCompare(b,'en'))){
  if(!folder||entry.dev)continue;
  const location=path.join(root,folder);
  const license=(await readdir(location)).find(name=>/^licen[cs]e(?:\.(?:txt|md))?$/i.test(name));
  if(!license)throw new Error(`Missing license for ${folder}; inspect it before shipping.`);
  notices.push(`\n${folder.replace(/^node_modules\//,'')} ${entry.version} (${entry.license})\n${await readFile(path.join(location,license),'utf8')}`);
}
await writeFile(path.join(vendor,'CODE-EDITOR-NOTICES.txt'),notices.join('\n'));
